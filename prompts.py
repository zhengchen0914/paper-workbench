DEFAULT_PRESET = "deep"


def preset_options() -> list[dict[str, str]]:
    """给模板下拉框用。"""
    return [
        {"key": key, "name": value["name"], "hint": value["hint"]}
        for key, value in ARTICLE_PRESETS.items()
    ]


def get_preset(key: str | None) -> tuple[str, dict[str, str]]:
    if key in ARTICLE_PRESETS:
        return key, ARTICLE_PRESETS[key]
    return DEFAULT_PRESET, ARTICLE_PRESETS[DEFAULT_PRESET]


def build_article_messages(
    reading: dict[str, Any],
    paper: dict[str, Any] | None,
    *,
    angle: str = "",
    preset: str = DEFAULT_PRESET,
) -> list[dict[str, str]]:
    """解读 → 公众号正文（按选定的结构模板）。"""
    preset_key, preset_def = get_preset(preset)
    system = ARTICLE_SYSTEM.replace("{{STRUCTURE}}", preset_def["structure"])
    length_block = (
        "## 篇幅（硬约束）\n\n"
        f"{preset_def['words']}\n"
        f"目标区间 {preset_def['min']}–{preset_def['max']} 字。"
        f"超过 {preset_def['max']} 字视为不合格：优先删掉重复论证与铺垫，不要删数字和结论。"
    )
    budget = preset_def.get("budget", "")
    if budget:
        length_block += "\n\n各节字数上限：\n" + budget
        length_block += (
            "\n\n写完后按实际字数自查一遍：任何一节超出上限就地压缩，"
            "全篇超过上限就删重复论证。不要输出压缩过程。"
        )
    system = system.replace("{{LENGTH}}", length_block)

    hints: list[str] = []
    if paper:
        hints.append(f"论文文件：{paper.get('filename', '')}")
        if paper.get("venue"):
            hints.append(f"出处：{paper['venue']}")
    hints.append(f"解读标题：{reading.get('title', '')}")
    hints.append(f"文章类型：{preset_def['name']}")
    if angle.strip():
        hints.append(f"本篇侧重：{angle.strip()}")

    user = (
        "把下面这份论文解读改写成公众号文章。\n\n"
        "## 背景信息\n" + "\n".join(hints) + "\n\n"
        "## 论文解读原文\n"
        f"{reading.get('content', '')}"
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


