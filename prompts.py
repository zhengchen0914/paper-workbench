def build_reading_messages(
    paper: dict[str, Any],
    paper_text: str,
    *,
    truncated: bool = False,
    focus: str = "",
) -> list[dict[str, str]]:
    """组装精读请求。paper 为 papers 表的一行。"""
    hints: list[str] = [
        f"文件：{paper.get('filename') or '未知'}",
        f"页数：{paper.get('pages') or '未知'}",
    ]
    if paper.get("venue"):
        hints.append(f"已知出处：{paper['venue']}")
    if paper.get("theme"):
        hints.append(f"所属主题：{paper['theme']}")
    if truncated:
        hints.append("注意：原文因长度限制被截断，未覆盖部分不要臆测内容")

    note = ""
    if focus.strip():
        note = f"\n\n## 本次额外关注\n{focus.strip()}"

    user = (
        "请按系统提示规定的格式，为下面这篇论文撰写完整的中文解读。\n\n"
        f"## 论文信息\n" + "\n".join(hints) + note + "\n\n"
        "## 论文全文（含页码标记）\n"
        f"{paper_text}"
    )
    return [
        {"role": "system", "content": READING_SYSTEM},
        {"role": "user", "content": user},
    ]


def build_dsh_task(paper: dict[str, Any], *, truncated: bool, focus: str = "") -> str:
    """生成交给 DSH 会话执行的任务说明（引擎切换用）。"""
    lines = [
        "# 论文解读任务（交给 DSH）",
        "",
        f"- 论文文件：`{paper.get('path', '')}`",
        f"- 页数：{paper.get('pages', 0)}",
        f"- 期望产出：严格遵循 `paper-reading-skill/SKILL.md` 的 8 段格式",
    ]
    if truncated:
        lines.append("- 注意：全文超过上下文上限，需分段阅读后合并")
    if focus.strip():
        lines += ["", "## 额外关注", focus.strip()]
    lines += [
        "",
        "## 执行方式",
        "",
        "把这份文件的内容连同上面的要求发进会话即可；",
        "产出后回到工作台，粘贴进稿件台的编辑框并保存。",
    ]
    return "\n".join(lines)


